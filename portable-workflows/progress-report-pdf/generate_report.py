    # Footer: light rule, author left, page number right
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 46, PAGE_W - MARGIN, 46)
    canvas.setFont("FreeSerif", 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 34, "Free Trader Project")
    body_start = getattr(doc, "_body_start_page", None)
    if body_start is not None and doc.page >= body_start:
        label = str(doc.page - body_start + 1)
    else:
        label = ROMAN.get(doc.page, str(doc.page))
    canvas.drawRightString(PAGE_W - MARGIN, 34, label)
    canvas.restoreState()


