def add_heading(text, style, level=0, body_start=False):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    if body_start:
        p.body_start = True
    return p


def chapter(num, title, first_para=None, body_start=False):
    """Chapter heading: conditional break + heading + accent rule."""
    els = []
    if body_start or num > 1:
        els.append(CondPageBreak(H1_ORPHAN))
    head = add_heading("%d. %s" % (num, title), h1_style, level=0, body_start=body_start)
    rule = HRFlowable(width="100%", thickness=1.2, color=ACCENT,
                      spaceBefore=5, spaceAfter=12)
    if first_para is not None:
        els.append(KeepTogether([Spacer(1, 10), head, rule, first_para]))
    else:
        els.append(KeepTogether([Spacer(1, 10), head, rule]))
    return els


def h2(text, first_para=None):
    head = add_heading(text, h2_style, level=1)
    if first_para is not None:
        return [KeepTogether([head, first_para])]
    return [head]


