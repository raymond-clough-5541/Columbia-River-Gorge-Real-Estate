_fig_n = [0]


def shot_figure(fname, caption_text, max_h=None):
    path = os.path.join(SHOTS, fname)
    if not os.path.exists(path):
        missing = Paragraph(
            "Capture not found on this machine: %s" % fname, caption_style)
        return [Spacer(1, 4), missing, Spacer(1, 8)]
    pil = PILImage.open(path)
    ow, oh = pil.size
    if max_h is None:
        # Landscape desktop captures: cap height at 270pt (still ~96% of
        # the content width). Portrait phone captures: allow a taller
        # 330pt so they display meaningfully.
        max_h = 330 if ow < 700 else 270
    max_w = AVAIL_W
    ratio = min(max_w / ow, max_h / oh, 1.0)
    img = Image(path, width=ow * ratio, height=oh * ratio)
    img.hAlign = "CENTER"
    _fig_n[0] += 1
    cap = Paragraph(
        "Figure %d. %s <font size=7.5>(gallery file: %s)</font>"
        % (_fig_n[0], caption_text, fname), caption_style)
    block = KeepTogether([Spacer(1, 6), img, Spacer(1, 2), cap])
    return [block, Spacer(1, 12)]


def data_table(header, rows, col_ratios, caption_text=None):
    w = AVAIL_W * 0.98
    col_widths = [r * w for r in col_ratios]
    assert abs(sum(col_widths) - w) < 1.0
    data = [[Paragraph("<b>%s</b>" % h, th_style) for h in header]]
    for r in rows:
        data.append([Paragraph(c, td_style) for c in r])
    t = Table(data, colWidths=col_widths, repeatRows=1, hAlign="CENTER")
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 12), t]
    if caption_text:
        out += [Spacer(1, 6), Paragraph(caption_text, caption_style)]
    out.append(Spacer(1, 14))
    return out


